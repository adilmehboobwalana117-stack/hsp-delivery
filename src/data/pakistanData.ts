function currentMonthIso(dayOfMonth: number, hour: number, minute: number): string {
  const now = new Date();
  const safeDay = Math.min(Math.max(1, dayOfMonth), Math.max(1, now.getDate()));
  const dt = new Date(now.getFullYear(), now.getMonth(), safeDay, hour, minute, 0);
  return dt.toISOString();
}

